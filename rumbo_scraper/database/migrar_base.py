"""Move the scraper's database to a new Supabase project.

    python -m rumbo_scraper.database.migrar_base esquema
    python -m rumbo_scraper.database.migrar_base bajar [tabla ...]
    python -m rumbo_scraper.database.migrar_base subir [tabla ...]

The old project (``SUPABASE_URL`` / ``SUPABASE_SECRET_KEY``) is read once, only
when its egress quota is back; the new one is ``NUEVA_SUPABASE_URL`` /
``NUEVA_SUPABASE_SECRET_KEY`` in ``.env``.

``esquema`` reads the old project's OpenAPI description (a few kilobytes of
egress) and writes ``data/migracion/esquema.json`` and ``esquema.sql``: the
tables, their types, primary keys, defaults, foreign keys and the unique
constraints the loaders' ``on_conflict`` need. Run the SQL in the new
project's SQL editor. ``bajar`` writes each table to
``data/migracion/<tabla>.jsonl`` a page at a time and resumes where it
stopped (each page is egress: a table already downloaded is never read
again). ``subir`` inserts those files into the new project in the order the
foreign keys ask for.
"""

from __future__ import annotations

import json
import os
import re
import sys
import time
from pathlib import Path
from typing import Any

MIGRACION = Path("data/migracion")
PAGINA = 1000
LOTE = 500

# What the loaders' ``on_conflict`` need and the API's description does not
# carry: the unique constraints.
UNICAS: dict[str, list[tuple[str, ...]]] = {
    "localidades": [("nombre_localidad", "provincia")],
    "universidades": [("nombre_oficial",)],
    "sedes": [("universidad_id", "nombre_sede")],
    "carreras": [("universidad_id", "nombre_carrera")],
    "ciclos_ingreso": [("oferta_id", "ciclo_anio", "ciclo_nombre")],
    "areas_tematicas": [("nombre",)],
    "posgrados": [("universidad_id", "nombre_programa")],
    "facultades": [("universidad_id", "nombre_facultad", "tipo_unidad")],
    "facultades_sedes": [("facultad_id", "sede_id")],
    "pendientes_datos": [("clave",)],
    "materias_catalogo_vinculos": [("materia_id", "materia_catalogo_id")],
}

_TIPOS = {
    "uuid": "uuid", "text": "text", "character varying": "text", "character": "text", "citext": "text",
    "integer": "integer", "bigint": "bigint", "smallint": "smallint", "numeric": "numeric",
    "double precision": "double precision", "real": "real", "boolean": "boolean",
    "date": "date", "time without time zone": "time", "timestamp without time zone": "timestamp",
    "timestamp with time zone": "timestamptz", "jsonb": "jsonb", "json": "json",
}
_DEFAULT_SEGURO = re.compile(r"^(?:now\(\)|gen_random_uuid\(\)|uuid_generate_v4\(\)|true|false|-?\d+(?:\.\d+)?"
                             r"|'[^']*'(?:::[a-z ]+)?|CURRENT_TIMESTAMP)$", re.I)


def _ident(nombre: str) -> str:
    return '"' + nombre.replace('"', '""') + '"'


def esquema_sql(openapi: dict[str, Any]) -> tuple[str, dict[str, Any]]:
    """The SQL that creates what the old project's OpenAPI description lists, and the tables in the order
    their foreign keys ask for."""
    tablas: dict[str, dict[str, Any]] = {}
    for nombre, definicion in (openapi.get("definitions") or {}).items():
        propiedades = definicion.get("properties") or {}
        if not propiedades:
            continue
        columnas = []
        for columna, p in propiedades.items():
            descripcion = p.get("description") or ""
            tipo = _TIPOS.get(p.get("format", ""), None)
            if p.get("type") == "array":
                base = _TIPOS.get((p.get("items") or {}).get("format", ""), "text")
                tipo = f"{base}[]"
            if tipo is None:
                tipo = {"integer": "integer", "number": "numeric", "boolean": "boolean",
                        "object": "jsonb"}.get(p.get("type", ""), "text")
            fk = re.search(r"<fk table='([^']+)' column='([^']+)'", descripcion)
            columnas.append({"nombre": columna, "tipo": tipo, "pk": "<pk/>" in descripcion,
                             "obligatoria": columna in (definicion.get("required") or []),
                             "default": p.get("default"), "fk": (fk.group(1), fk.group(2)) if fk else None})
        tablas[nombre] = {"columnas": columnas}

    def depende(nombre: str) -> set[str]:
        return {c["fk"][0] for c in tablas[nombre]["columnas"] if c["fk"] and c["fk"][0] in tablas
                and c["fk"][0] != nombre}

    orden: list[str] = []
    pendientes = set(tablas)
    while pendientes:
        listas = sorted(t for t in pendientes if depende(t) <= set(orden))
        if not listas:  # a cycle: its foreign keys go in as ALTERs after all the tables
            listas = sorted(pendientes)[:1]
        orden += listas
        pendientes -= set(listas)

    sql = ["-- Generated by rumbo_scraper.database.migrar_base from the old project's OpenAPI description."]
    for nombre in orden:
        columnas = tablas[nombre]["columnas"]
        lineas = []
        for c in columnas:
            linea = f"  {_ident(c['nombre'])} {c['tipo']}"
            if c["default"] is not None and _DEFAULT_SEGURO.match(str(c["default"])):
                linea += f" default {c['default']}"
            if c["obligatoria"] and c["default"] is None and not c["pk"]:
                linea += " not null"
            lineas.append(linea)
        claves = [_ident(c["nombre"]) for c in columnas if c["pk"]]
        if claves:
            lineas.append(f"  primary key ({', '.join(claves)})")
        sql.append(f"create table if not exists {_ident(nombre)} (\n" + ",\n".join(lineas) + "\n);")
    for nombre in orden:
        for c in tablas[nombre]["columnas"]:
            if c["fk"] and c["fk"][0] in tablas:
                sql.append(f"alter table {_ident(nombre)} add foreign key ({_ident(c['nombre'])}) "
                           f"references {_ident(c['fk'][0])} ({_ident(c['fk'][1])});")
    for nombre, grupos in UNICAS.items():
        if nombre not in tablas:
            continue
        existentes = {c["nombre"] for c in tablas[nombre]["columnas"]}
        for grupo in grupos:
            if set(grupo) <= existentes:
                sql.append(f"create unique index if not exists {_ident('uq_' + nombre + '_' + '_'.join(grupo))} "
                           f"on {_ident(nombre)} ({', '.join(_ident(g) for g in grupo)});")
    sql.append("notify pgrst, 'reload schema';")
    return "\n".join(sql) + "\n", {"orden": orden, "tablas": tablas}


def orden_de_subida(esquema: dict[str, Any]) -> list[str]:
    return list(esquema["orden"])


def _cliente(nueva: bool) -> Any:
    from supabase import create_client

    prefijo = "NUEVA_" if nueva else ""
    url = os.getenv(prefijo + "SUPABASE_URL", "").strip().rstrip("/")
    clave = (os.getenv(prefijo + "SUPABASE_SECRET_KEY") or os.getenv(prefijo + "SUPABASE_SERVICE_ROLE_KEY") or "").strip()
    if not (url and clave):
        raise SystemExit(f"Faltan {prefijo}SUPABASE_URL y {prefijo}SUPABASE_SECRET_KEY en el .env")
    return create_client(re.sub(r"/rest/v1$", "", url), clave)


def comando_esquema() -> None:
    import httpx
    from dotenv import load_dotenv

    load_dotenv()
    url = os.getenv("SUPABASE_URL", "").strip().rstrip("/")
    clave = (os.getenv("SUPABASE_SECRET_KEY") or os.getenv("SUPABASE_SERVICE_ROLE_KEY") or "").strip()
    respuesta = httpx.get(f"{re.sub(r'/rest/v1$', '', url)}/rest/v1/", headers={"apikey": clave, "Authorization": f"Bearer {clave}"},
                          timeout=60)
    if respuesta.status_code != 200:
        raise SystemExit(f"La base vieja todavía no responde: HTTP {respuesta.status_code}")
    MIGRACION.mkdir(parents=True, exist_ok=True)
    (MIGRACION / "openapi.json").write_text(respuesta.text)
    sql, estructura = esquema_sql(respuesta.json())
    (MIGRACION / "esquema.sql").write_text(sql)
    (MIGRACION / "esquema.json").write_text(json.dumps(estructura, indent=1, default=str))
    print(f"{sql.count('create table')} tablas -> {MIGRACION / 'esquema.sql'} (correrlo en el SQL editor de la base nueva)")


def comando_bajar(tablas: list[str]) -> None:
    from dotenv import load_dotenv

    load_dotenv()
    esquema = json.loads((MIGRACION / "esquema.json").read_text())
    cliente = _cliente(False)
    for tabla in tablas or orden_de_subida(esquema):
        archivo = MIGRACION / f"{tabla}.jsonl"
        hechas = sum(1 for _ in archivo.open()) if archivo.exists() else 0
        pk = next((c["nombre"] for c in esquema["tablas"][tabla]["columnas"] if c["pk"]), None)
        total = hechas
        with archivo.open("a") as salida:
            while True:
                consulta = cliente.table(tabla).select("*")
                if pk:
                    consulta = consulta.order(pk)
                filas = consulta.range(total, total + PAGINA - 1).execute().data
                for fila in filas:
                    salida.write(json.dumps(fila, ensure_ascii=False) + "\n")
                salida.flush()
                total += len(filas)
                if len(filas) < PAGINA:
                    break
        print(f"{tabla}: {total} filas", flush=True)


def comando_subir(tablas: list[str]) -> None:
    from dotenv import load_dotenv

    load_dotenv()
    esquema = json.loads((MIGRACION / "esquema.json").read_text())
    cliente = _cliente(True)
    for tabla in tablas or orden_de_subida(esquema):
        archivo = MIGRACION / f"{tabla}.jsonl"
        if not archivo.exists():
            continue
        filas = [json.loads(linea) for linea in archivo.open() if linea.strip()]
        for inicio in range(0, len(filas), LOTE):
            cliente.table(tabla).upsert(filas[inicio:inicio + LOTE]).execute()
            time.sleep(0.2)
        print(f"{tabla}: {len(filas)} filas subidas", flush=True)


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in ("esquema", "bajar", "subir"):
        raise SystemExit(__doc__)
    {"esquema": comando_esquema, "bajar": lambda: comando_bajar(sys.argv[2:]),
     "subir": lambda: comando_subir(sys.argv[2:])}[sys.argv[1]]()


if __name__ == "__main__":
    main()
